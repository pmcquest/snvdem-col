#================================================================================
# Figure D.2 -- Democracy scores by municipality decile
#================================================================================

decile_plot <- function(data, varname, ylab, subtitle, title) {
  dec <- data %>%
    filter(!is.na(.data[[varname]])) %>%
    group_by(year) %>%
    mutate(decile = ntile(.data[[varname]], 10)) %>%
    group_by(year, decile) %>%
    summarise(mean_score = mean(.data[[varname]], na.rm = TRUE), .groups = "drop")

  ggplot(dec, aes(x = year, y = mean_score, group = decile, color = as.factor(decile))) +
    geom_line(alpha = 0.7, linewidth = 1) +
    scale_color_viridis_d(option = "D", direction = -1) +
    labs(title = title, subtitle = subtitle, y = ylab, x = "Year", color = "Decile") +
    theme_minimal()
}

