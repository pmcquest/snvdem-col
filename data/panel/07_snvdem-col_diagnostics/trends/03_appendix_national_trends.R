norm01 <- function(x) (x - min(x, na.rm = TRUE)) / (max(x, na.rm = TRUE) - min(x, na.rm = TRUE))

#================================================================================
# Figure D.1 -- National mean scores over time
#================================================================================

national_avg_plot <- function(data, el_col, cl_col, overall_col, subtitle, title) {
  nat_avg <- data %>%
    group_by(year) %>%
    summarise(Electoral = mean(.data[[el_col]], na.rm = TRUE),
              CivilLib  = mean(.data[[cl_col]], na.rm = TRUE),
              Overall   = mean(.data[[overall_col]], na.rm = TRUE)) %>%
    pivot_longer(cols = -year, names_to = "Index", values_to = "Score")

  ggplot(nat_avg, aes(x = year, y = Score, color = Index, linetype = Index)) +
    geom_line(linewidth = 1.2) +
    geom_point() +
    scale_color_manual(values = c("Electoral" = "#2c7bb6", "CivilLib" = "#d7191c", "Overall" = "black")) +
    labs(title = title, subtitle = subtitle, y = "Mean Score", x = "Year") +
    theme_minimal()
}

#---- D.1 (pre-benchmark): matches the original figure's own 0-1 min-max normalization ----
prebench <- snvdem_final %>%
  filter(!is.na(snelect) & !is.na(sncivlib) & !is.na(sndem)) %>%
  mutate(snelect_norm = norm01(snelect), sncivlib_norm = norm01(sncivlib), sndem_norm = norm01(sndem))

figD1a <- national_avg_plot(prebench, "snelect_norm", "sncivlib_norm", "sndem_norm",
